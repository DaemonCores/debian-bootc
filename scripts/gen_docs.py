#!/usr/bin/env python3
"""gen_docs.py — generate the technical reference from source comments.

Usage:
    python3 scripts/gen_docs.py [--check]

Reads the Google-style docstrings of the Python sources and the header comment
block of every shell script, and rewrites the generated region of
``docs/reference/Reference-Python.md`` and
``docs/reference/Reference-Shell.md``.
With ``--check`` nothing is written and the exit status is 1 when a page is
out of date (used by CI).
"""

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "docs" / "reference"
START = "<!-- gen:reference start -->"
END = "<!-- gen:reference end -->"
SHELL_SHEBANG = re.compile(r"^#!.*(ba)?sh")


def _read_makefile_list(name: str) -> list[str]:
    """Return the paths listed under the Makefile variable ``name``.

    Args:
        name: Makefile variable assigned with backslash continuation lines.

    Returns:
        The listed paths, in declaration order.
    """
    text = (ROOT / "Makefile").read_text(encoding="utf-8")
    block = re.search(rf"^{name} :=((?:.*\\\n)*.*)$", text, re.MULTILINE)
    if block is None:
        return []
    return re.findall(r"[\w./-]+/[\w./-]+|[\w-]+\.py", block.group(1))


def _python_section(path: Path) -> str:
    """Render the Markdown reference of one Python source file.

    Args:
        path: Python file to document.

    Returns:
        Markdown for the module docstring and each documented function.
    """
    rel = path.relative_to(ROOT)
    tree = ast.parse(path.read_text(encoding="utf-8"))
    parts = [f"## `{rel}`\n"]
    parts.append((ast.get_docstring(tree) or "(no module docstring)") + "\n")
    for node in tree.body:
        if isinstance(node, ast.FunctionDef):
            doc = ast.get_docstring(node) or "(no docstring)"
            parts.append(f"### `{node.name}()`\n\n```text\n{doc}\n```\n")
    return "\n".join(parts)


def _shell_header(path: Path) -> str:
    """Return the leading comment block of a shell script.

    Args:
        path: Shell script to read.

    Returns:
        The comment lines after the shebang, without the leading ``# ``.
    """
    lines: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if SHELL_SHEBANG.match(line) or (not lines and line == "#"):
            continue
        if not line.startswith("#"):
            break
        lines.append(line[2:] if line.startswith("# ") else "")
    return "\n".join(lines).strip() or "(no header comment)"


def _shell_section(path: Path) -> str:
    """Render the Markdown reference of one shell script.

    Args:
        path: Shell script to document.

    Returns:
        Markdown with the script path and its header comment.
    """
    rel = path.relative_to(ROOT)
    return f"## `{rel}`\n\n{_shell_header(path)}\n"


def _page(title: str, body: str, current: str) -> str:
    """Splice ``body`` into the generated region of an existing page.

    Args:
        title: Page title, used when the page does not exist yet.
        body: Generated Markdown.
        current: Current page content ("" when absent).

    Returns:
        The full page content.
    """
    region = f"{START}\n\n{body}\n{END}"
    if START in current and END in current:
        head, _, rest = current.partition(START)
        _, _, tail = rest.partition(END)
        return head + region + tail
    return (
        f"# {title}\n\nGenerated by `make docs` from source comments; "
        f"do not edit between the markers.\n\n{region}\n"
    )


def main() -> int:
    """Entry point: write (or check) the reference pages.

    Returns:
        Process exit status.
    """
    check = "--check" in sys.argv[1:]
    py_files = [ROOT / p for p in _read_makefile_list("PYTHON_SRCS")]
    sh_files = [
        ROOT / p for p in _read_makefile_list("SHELL_SRCS") +
        _read_makefile_list("POSTINST_SRCS")
    ]
    pages = {
        "Reference-Python.md":
        ("Python reference", "\n".join(map(_python_section, py_files))),
        "Reference-Shell.md":
        ("Shell reference", "\n".join(map(_shell_section, sh_files))),
    }
    stale = False
    for name, (title, body) in pages.items():
        target = OUT_DIR / name
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        new = _page(title, body, current)
        if new == current:
            continue
        stale = True
        if not check:
            OUT_DIR.mkdir(parents=True, exist_ok=True)
            target.write_text(new, encoding="utf-8")
    if check and stale:
        print("docs/reference is out of date: run `make docs`", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
